def get_trans(lang, key):
    # Check for dynamic override in settings (e.g. txt_order_taxi_uz)
    override_key = f"txt_{key}_{lang}"
    custom = get_setting_sync(override_key)
    if custom:
        # logging.debug(f"Using dynamic override for {override_key}")
        return custom
        
    # Fallback to uz if language or key not found
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS['uz'])
    result = lang_dict.get(key, TRANSLATIONS['uz'].get(key))
    
    if result:
        return result
    
    # SAFETY FALLBACK: Never show raw technical keys
    if "msg" in key.lower() or "_" in key:
        # If it looks like a technical key, return a generic friendly message
        fallbacks = {
            'uz': "ℹ️ Ma'lumot yuklanmoqda...",
            'ru': "ℹ️ Загрузка информации...",
            'en': "ℹ️ Loading information..."
        }
        return fallbacks.get(lang, fallbacks['uz'])
        
    return key
